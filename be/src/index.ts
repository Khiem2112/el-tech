import cors from 'cors';
import express from 'express';
import { environment } from './config.js';
import { success } from './contracts/api.js';
import { correlationId, errorHandler } from './middleware/error-handler.js';
import { catalogRouter } from './routes/catalog.routes.js';
import { cartRouter } from './routes/cart.routes.js';
import { checkoutRouter } from './routes/checkout.routes.js';
import { orderRouter } from './routes/order.routes.js';
import { paymentRouter } from './routes/payment.routes.js';
import { orderLookupRouter } from './routes/order-lookup.routes.js';
import { reviewRouter } from './routes/review.routes.js';
import { pcBuildRouter } from './routes/pc-build.routes.js';
import { adminAuthRouter } from './routes/admin/admin-auth.routes.js';
import { adminBranchRouter } from './routes/admin/branch.routes.js';
import { adminBrandRouter } from './routes/admin/brand.routes.js';
import { adminCategoryRouter } from './routes/admin/category.routes.js';
import { adminProductTemplateRouter } from './routes/admin/product-template.routes.js';
import { adminProductVariantRouter } from './routes/admin/product-variant.routes.js';
import { adminPcBundleRouter } from './routes/admin/pc-bundle.routes.js';
import { adminSupplierRouter } from './routes/admin/supplier.routes.js';
import { adminPurchaseOrderRouter } from './routes/admin/purchase-order.routes.js';
import { adminSupplierReturnRouter } from './routes/admin/supplier-return.routes.js';
import { variantCatalogRouter } from './routes/admin/variant-catalog.routes.js';
import { adminInventoryRouter } from './routes/admin/inventory.routes.js';
import { adminSerialRouter } from './routes/admin/serial.routes.js';
import { adminTransferRouter } from './routes/admin/transfer.routes.js';
import { adminOrderRouter } from './routes/admin/order.routes.js';
import { adminPromotionRouter } from './routes/admin/promotion.routes.js';
import { adminCouponRouter } from './routes/admin/coupon.routes.js';
import { adminDeliveryFeeRouter } from './routes/admin/delivery-fee.routes.js';

const app = express();
const corsOrigin = environment.CORS_ORIGIN === '*' ? true : environment.CORS_ORIGIN;
app.use(cors({ origin: corsOrigin, credentials: true }));
app.use(express.json({ limit: '1mb' }));
app.use(correlationId);
app.get('/health', (_request, response): void => { response.json(success({ status: 'ok' }, response.locals.correlationId as string)); });
app.use('/v1', catalogRouter);
app.use('/v1', cartRouter);
app.use('/v1', checkoutRouter);
app.use('/v1', orderRouter);
app.use('/v1', paymentRouter);
app.use('/v1', orderLookupRouter);
app.use('/v1', reviewRouter);
app.use('/v1', pcBuildRouter);
app.use('/api/admin/auth', adminAuthRouter);
app.use('/v1/admin/auth', adminAuthRouter);
app.use('/api/admin/branches', adminBranchRouter);
app.use('/v1/admin/branches', adminBranchRouter);
app.use('/api/admin/categories', adminCategoryRouter);
app.use('/v1/admin/categories', adminCategoryRouter);
app.use('/api/admin/brands', adminBrandRouter);
app.use('/v1/admin/brands', adminBrandRouter);
app.use('/api/admin/product-templates', adminProductTemplateRouter);
app.use('/v1/admin/product-templates', adminProductTemplateRouter);
app.use('/api/admin/product-variants', adminProductVariantRouter);
app.use('/v1/admin/product-variants', adminProductVariantRouter);
app.use('/api/admin/pc-bundles', adminPcBundleRouter);
app.use('/v1/admin/pc-bundles', adminPcBundleRouter);
app.use('/api/admin/suppliers', adminSupplierRouter);
app.use('/v1/admin/suppliers', adminSupplierRouter);
app.use('/api/admin/purchase-orders', adminPurchaseOrderRouter);
app.use('/v1/admin/purchase-orders', adminPurchaseOrderRouter);
app.use('/api/admin/supplier-returns', adminSupplierReturnRouter);
app.use('/v1/admin/supplier-returns', adminSupplierReturnRouter);
app.use('/api/admin/catalog/variants', variantCatalogRouter);
app.use('/v1/admin/catalog/variants', variantCatalogRouter);
app.use('/api/admin/inventory', adminInventoryRouter);
app.use('/v1/admin/inventory', adminInventoryRouter);
app.use('/api/admin/serials', adminSerialRouter);
app.use('/v1/admin/serials', adminSerialRouter);
app.use('/api/admin/inventory/serials', adminSerialRouter);
app.use('/v1/admin/inventory/serials', adminSerialRouter);
app.use('/api/admin/transfers', adminTransferRouter);
app.use('/v1/admin/transfers', adminTransferRouter);
app.use('/api/admin/inventory/transfers', adminTransferRouter);
app.use('/v1/admin/inventory/transfers', adminTransferRouter);
app.use('/api/admin/orders', adminOrderRouter);
app.use('/v1/admin/orders', adminOrderRouter);
app.use('/api/admin/promotions', adminPromotionRouter);
app.use('/v1/admin/promotions', adminPromotionRouter);
app.use('/api/admin/coupons', adminCouponRouter);
app.use('/v1/admin/coupons', adminCouponRouter);
app.use('/api/admin/delivery-fees', adminDeliveryFeeRouter);
app.use('/v1/admin/delivery-fees', adminDeliveryFeeRouter);
app.use('/api/admin/shipping-fees', adminDeliveryFeeRouter);
app.use('/v1/admin/shipping-fees', adminDeliveryFeeRouter);
app.use(errorHandler);

if (!process.env.VERCEL) {
  app.listen(environment.PORT, (): void => {
    console.info(`EL-TECH API listening on port ${environment.PORT}`);
  });
}

export default app;
